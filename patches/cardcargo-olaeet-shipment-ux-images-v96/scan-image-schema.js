const fs = require('fs')
const path = require('path')

const appRoot = process.argv[2]
if (!appRoot) throw new Error('APP_ROOT missing.')

const generated = path.join(appRoot, 'lib', 'olaeet-image-schema.generated.ts')

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.next', '.git'].includes(entry.name)) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (/\.(ts|tsx|js|jsx)$/.test(entry.name)) out.push(full)
  }
  return out
}

const packageImageTables = new Set([
  'warehouse_package_images',
  'package_images',
  'olaeet_package_images',
  'warehouse_images',
  'package_photos',
])
const packagePurchaseTables = new Set([
  'warehouse_package_purchases',
  'purchase_warehouse_packages',
  'warehouse_package_purchase_links',
  'package_purchases',
  'purchase_package_links',
])
const buckets = new Set([
  'listing-images',
  'warehouse-package-images',
  'package-images',
  'olaeet-images',
])

for (const root of [path.join(appRoot, 'app'), path.join(appRoot, 'components'), path.join(appRoot, 'lib')]) {
  for (const file of walk(root)) {
    if (file === generated) continue
    const source = fs.readFileSync(file, 'utf8')
    const lowerPath = file.toLowerCase()
    const packageContext = lowerPath.includes('warehouse-package') || lowerPath.includes('warehouse_package') || /manualimages|packageimages/i.test(source)

    for (const match of source.matchAll(/\.from\(\s*['"]([a-zA-Z0-9_-]+)['"]\s*\)/g)) {
      const table = match[1]
      const around = source.slice(Math.max(0, match.index - 700), Math.min(source.length, match.index + 1200))
      if (packageContext && /image|photo|storage_path|signed_url|manualimages/i.test(`${table} ${around}`)) {
        if (table !== 'purchase_images' && /image|photo|media/i.test(table)) packageImageTables.add(table)
      }
      if (packageContext && /purchase/i.test(table) && /package|warehouse/i.test(table)) {
        packagePurchaseTables.add(table)
      }
    }

    for (const match of source.matchAll(/storage\s*\.\s*from\(\s*['"]([^'"]+)['"]\s*\)/g)) {
      buckets.add(match[1])
    }
  }
}

const output = `// Auto-generated by CardCargo v96 apply.sh.\nexport const packageImageTableCandidates = ${JSON.stringify([...packageImageTables], null, 2)} as const\n\nexport const packagePurchaseRelationTableCandidates = ${JSON.stringify([...packagePurchaseTables], null, 2)} as const\n\nexport const imageBucketCandidates = ${JSON.stringify([...buckets], null, 2)} as const\n`

fs.mkdirSync(path.dirname(generated), { recursive: true })
fs.writeFileSync(generated, output)
console.log(`Image schema generated: ${path.relative(appRoot, generated)}`)
console.log(`  package image tables: ${[...packageImageTables].join(', ')}`)
console.log(`  package/purchase links: ${[...packagePurchaseTables].join(', ')}`)
console.log(`  storage buckets: ${[...buckets].join(', ')}`)
