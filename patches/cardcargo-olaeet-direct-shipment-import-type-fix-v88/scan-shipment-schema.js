const fs = require('fs')
const path = require('path')

const appRoot = process.argv[2]
if (!appRoot) throw new Error('APP_ROOT fehlt.')

const generatedRel =
  'lib/olaeet-shipment-schema.generated.ts'
const generatedFile = path.join(
  appRoot,
  generatedRel,
)

function walk(dir, output = []) {
  if (!fs.existsSync(dir)) return output

  for (const entry of fs.readdirSync(dir, {
    withFileTypes: true,
  })) {
    if (
      ['node_modules', '.next', '.git'].includes(
        entry.name,
      )
    ) {
      continue
    }

    const full = path.join(dir, entry.name)

    if (entry.isDirectory()) {
      walk(full, output)
    } else if (
      /\.(ts|tsx|js|jsx)$/.test(entry.name)
    ) {
      output.push(full)
    }
  }

  return output
}

const shipmentTables = new Set([
  'shipments',
  'international_shipments',
  'outbound_shipments',
])

const relationTables = new Set([
  'shipment_warehouse_packages',
  'international_shipment_packages',
  'outbound_shipment_packages',
  'shipment_packages',
  'warehouse_package_shipments',
])

function isSidecarOrAuxiliary(table) {
  return (
    table.startsWith('olaeet_shipment_') ||
    /(?:^|_)shipment_(?:images?|documents?|attachments?|events?|history|logs?|cost_|fee_|allocation|settings?)(?:_|$)/i.test(
      table,
    ) ||
    /(?:^|_)(?:images?|documents?|attachments?|events?|history|logs?|allocations?|settings?)_(?:.*_)?shipments?(?:_|$)/i.test(
      table,
    )
  )
}

function isShipmentPackageRelation(table) {
  return (
    /shipment.*package/i.test(table) ||
    /package.*shipment/i.test(table)
  )
}

function isTopLevelShipmentTable(table) {
  if (isSidecarOrAuxiliary(table)) {
    return false
  }

  if (isShipmentPackageRelation(table)) {
    return false
  }

  // Accept the conventional CardCargo names and similarly named future
  // top-level tables, but reject generic auxiliary tables merely containing
  // the word "shipment".
  return (
    table === 'shipments' ||
    table === 'international_shipments' ||
    table === 'outbound_shipments' ||
    /^(?:[a-z0-9]+_)*shipments$/i.test(table)
  )
}

for (const base of [
  path.join(appRoot, 'app'),
  path.join(appRoot, 'components'),
  path.join(appRoot, 'lib'),
]) {
  for (const file of walk(base)) {
    if (file === generatedFile) continue

    const source = fs.readFileSync(file, 'utf8')

    for (const match of source.matchAll(
      /\.from\(\s*['"]([a-zA-Z0-9_]+)['"]\s*\)/g,
    )) {
      const table = match[1]

      if (!/shipment/i.test(table)) {
        continue
      }

      if (isShipmentPackageRelation(table)) {
        if (!isSidecarOrAuxiliary(table)) {
          relationTables.add(table)
        }
        continue
      }

      if (isTopLevelShipmentTable(table)) {
        shipmentTables.add(table)
      }
    }
  }
}

const source = `// Auto-generated by CardCargo v88 apply.sh.
// Only top-level shipment tables and Shipment<->Package relation tables
// discovered from the local source are included.
export const shipmentTableCandidates = ${JSON.stringify(
  [...shipmentTables],
  null,
  2,
)} as const

export const shipmentPackageTableCandidates = ${JSON.stringify(
  [...relationTables],
  null,
  2,
)} as const
`

fs.writeFileSync(generatedFile, source)

console.log(
  `Shipment-Schema-Kandidaten erzeugt: ${generatedRel}`,
)
console.log(
  `  Shipment tables: ${[...shipmentTables].join(', ')}`,
)
console.log(
  `  Link tables: ${[...relationTables].join(', ')}`,
)
