const fs = require('fs')
const path = require('path')

const appRoot = process.argv[2]
if (!appRoot) throw new Error('APP_ROOT missing.')

const generated = path.join(appRoot, 'lib', 'olaeet-image-schema.generated.ts')

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.next', '.git'].includes(entry.name)) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (/\.(ts|tsx|js|jsx)$/.test(entry.name)) out.push(full)
  }
  return out
}

const packageImageTables = new Set([
  'warehouse_package_images',
  'package_images',
  'olaeet_package_images',
  'warehouse_images',
  'package_photos',
])

const packagePurchaseTables = new Set([
  'warehouse_package_purchases',
  'purchase_warehouse_packages',
  'warehouse_package_purchase_links',
  'package_purchases',
  'purchase_package_links',
])

const buckets = new Set([
  'listing-images',
  'warehouse-package-images',
  'package-images',
  'olaeet-images',
])

function looksLikePackageImageTable(table) {
  if (!/^[a-zA-Z0-9_]+$/.test(table)) return false
  if (/shipment|inventory|listing|purchase_images?/i.test(table)) return false
  return (
    /warehouse.*package.*(?:image|photo|media)/i.test(table) ||
    /(?:image|photo|media).*warehouse.*package/i.test(table) ||
    /^package_(?:images?|photos?|media)$/i.test(table) ||
    /^olaeet_(?:package_)?(?:images?|photos?|media)$/i.test(table) ||
    /^warehouse_(?:images?|photos?)$/i.test(table)
  )
}

function looksLikePackagePurchaseTable(table) {
  if (!/^[a-zA-Z0-9_]+$/.test(table)) return false
  return /purchase/i.test(table) && /package|warehouse/i.test(table)
}

for (const root of [
  path.join(appRoot, 'app'),
  path.join(appRoot, 'components'),
  path.join(appRoot, 'lib'),
  path.join(appRoot, 'src', 'app'),
  path.join(appRoot, 'src', 'components'),
  path.join(appRoot, 'src', 'lib'),
]) {
  for (const file of walk(root)) {
    if (file === generated) continue
    const source = fs.readFileSync(file, 'utf8')

    for (const match of source.matchAll(/\.from\(\s*['\"]([a-zA-Z0-9_-]+)['\"]\s*\)/g)) {
      const table = match[1]
      if (looksLikePackageImageTable(table)) packageImageTables.add(table)
      if (looksLikePackagePurchaseTable(table)) packagePurchaseTables.add(table)
    }

    for (const match of source.matchAll(/storage\s*\.\s*from\(\s*['\"]([^'\"]+)['\"]\s*\)/g)) {
      buckets.add(match[1])
    }
  }
}

const output = `// Auto-generated by CardCargo v97 apply.sh.\nexport const packageImageTableCandidates = ${JSON.stringify([...packageImageTables], null, 2)} as const\n\nexport const packagePurchaseRelationTableCandidates = ${JSON.stringify([...packagePurchaseTables], null, 2)} as const\n\nexport const imageBucketCandidates = ${JSON.stringify([...buckets], null, 2)} as const\n`

fs.mkdirSync(path.dirname(generated), { recursive: true })
fs.writeFileSync(generated, output)

console.log(`Image schema generated: ${path.relative(appRoot, generated)}`)
console.log(`  package image tables: ${[...packageImageTables].join(', ')}`)
console.log(`  package/purchase links: ${[...packagePurchaseTables].join(', ')}`)
console.log(`  storage buckets: ${[...buckets].join(', ')}`)
